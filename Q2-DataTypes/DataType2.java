// package Q2-DataTypes;

public class DataType2 {
    public static void main(String[] args) {
        int x = 10;
        System.out.println("The no is " + x); 
        float y = 10.5f;
        System.out.println("The float no is " + y);
        double z = 10.5d;
        System.out.println("The double no is " + z); 
        char c = 'A';
        System.out.println("The char is " + c); 
        String s = "Hello";
        System.out.println("The string is " + s); 
        boolean b = true;
        System.out.println("The boolean is " + b);
    }
}
